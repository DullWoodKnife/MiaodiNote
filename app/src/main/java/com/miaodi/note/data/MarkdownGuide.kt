## 十七、常用技巧与工具

- **换行**：行尾加两个空格，或使用空行分段。
- **强调与加粗**：不要滥用，保持文档简洁。
- **列表缩进**：子列表统一缩进，避免解析歧义。
- **图片与链接**：使用参考式写法便于统一维护地址。
- **常用编辑器**：Typora、VS Code、Obsidian、Notion 等均原生支持 Markdown。

