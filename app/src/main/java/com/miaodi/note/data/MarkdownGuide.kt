## 一、什么是 Markdown

Markdown 由约翰·格鲁伯（John Gruber）于 2004 年创建，核心设计理念是「易读易写」。

- **简洁性**：用直观的符号表示格式，例如 `#` 表示标题，`*` 表示列表。
- **可读性**：即使不渲染，纯文本也能清晰展现文档结构。
- **便携性**：纯文本格式，任何编辑器都能打开，不依赖特定软件。
- **转换性**：可轻松转换为 HTML、PDF、Word 等格式。

Markdown 并不是 HTML 的替代品，而是 HTML 的简化版本，它的最终目标就是转换为 HTML：

```
Markdown 源码 → 解析器 → HTML 输出 → 浏览器渲染
```

例如写下：

```
# 这是一个标题
```

会转换为：

```
<h1>这是一个标题</h1>
```

