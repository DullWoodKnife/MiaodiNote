## 三、段落与换行

- 段落：直接用空行分隔不同的段落。
- 换行：在行尾加两个或以上空格再换行，或者直接使用一个空行开启新段落。

示例：

```
这是第一段。段落之间用空行分隔。

这是第二段，与上一段之间有一个空行。
```

