## 六、列表

### 6.1 无序列表

使用 `*`、`+` 或 `-` 作为列表标记。

```
- 苹果
- 香蕉
- 橙子
```

### 6.2 有序列表

使用数字加英文句点，数字可以不连续。

```
1. 第一步
2. 第二步
3. 第三步
```

### 6.3 嵌套列表

在子列表前缩进（通常 2~4 个空格或一个 Tab）。

```
- 前端
  - HTML
  - CSS
  - JavaScript
- 后端
  - Java
  - Kotlin
```

### 6.4 任务列表（GFM 扩展）

```
- [x] 已完成的任务
- [ ] 未完成的任务
```

