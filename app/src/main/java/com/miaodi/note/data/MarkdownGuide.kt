## 七、引用

在段落前加 `>` 符号表示引用，支持多级嵌套。

```
> 这是一段引用。
> 引用可以换行。

> 一级引用
>> 二级引用
>>> 三级引用
```

引用中也可以包含标题、列表、代码等：

```
> ## 引用中的标题
> 1. 列表项一
> 2. 列表项二
```

