# Markdown 完全学习指南

> 本文参考菜鸟教程《Markdown 教程》：https://www.runoob.com/markdown/md-tutorial.html
> Markdown 是一种轻量级标记语言，允许人们使用易读易写的纯文本格式编写文档，可导出 HTML、Word、图像、PDF、Epub 等多种格式。

