## 十二、转义字符

当需要显示 Markdown 的特殊符号本身时，在其前面加上反斜杠 `\`：

```
\* 这里显示的是星号而不是斜体
\# 这里显示的是井号而不是标题
\[ 这里显示的是方括号
```

可转义的符号包括：`\`、`` ` ``、`*`、`_`、`{}`、`[]`、`()`、`#`、`+`、`-`、`.`、`!`、`|` 等。

---

## 十三、内嵌 HTML

Markdown 支持直接嵌入 HTML 标签，用于实现 Markdown 无法表达的复杂格式：

```
这是一个 <b>加粗</b> 的句子。
这是一个 <span style="color:red;">红色文字</span>。
```

大部分 Markdown 解析器都允许使用 HTML 标签。

---

## 十四、脚注

部分平台（如 GFM）支持脚注，语法如下：

```
这是一段需要说明的文字[^1]。

[^1]: 这里是脚注的具体内容。
```

