## 十一、表格

使用 `|` 分隔单元格，第二行用 `-` 定义对齐方式（`:` 控制左右对齐）。

```
| 左对齐 | 居中 | 右对齐 |
| :--- | :---: | ---: |
| 内容 | 内容 | 内容 |
| A | B | C |
```

渲染效果：

| 左对齐 | 居中 | 右对齐 |
| :--- | :---: | ---: |
| 内容 | 内容 | 内容 |
| A | B | C |

