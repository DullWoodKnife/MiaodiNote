## 四、字体样式

| 样式 | 语法 | 效果 |
| --- | --- | --- |
| 斜体 | `*文字*` 或 `_文字_` | *斜体文字* |
| 粗体 | `**文字**` 或 `__文字__` | **粗体文字** |
| 粗斜体 | `***文字***` | ***粗斜体文字*** |
| 删除线 | `~~文字~~` | ~~删除线文字~~ |
| 高亮（部分平台） | `==文字==` | ==高亮文字== |

示例：

```
*单星号是斜体*
_下划线是斜体_
**双星号是粗体**
__双下划线是粗体__
***三星号是粗斜体***
~~双波浪线是删除线~~
```

